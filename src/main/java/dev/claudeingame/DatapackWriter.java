package dev.claudeingame;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import net.minecraft.server.MinecraftServer;
import net.minecraft.util.WorldSavePath;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Set;

/** Записывает файлы, созданные Claude, в датапак world/datapacks/claude_generated. */
public final class DatapackWriter {
	public static final String PACK_NAME = "claude_generated";
	private static final Set<String> ALLOWED_EXT = Set.of(".json", ".mcfunction", ".txt");
	private static final int MAX_FILE_BYTES = 200_000;
	private static final int MAX_FILES = 40;

	private DatapackWriter() {}

	public static List<String> write(MinecraftServer server, JsonArray files) throws IOException {
		Path root = server.getSavePath(WorldSavePath.DATAPACKS).resolve(PACK_NAME).toAbsolutePath().normalize();
		Files.createDirectories(root);
		Path meta = root.resolve("pack.mcmeta");
		if (!Files.exists(meta)) {
			Files.writeString(meta, "{\"pack\":{\"pack_format\":15,\"description\":\"Generated by Claude\"}}", StandardCharsets.UTF_8);
		}
		List<String> written = new ArrayList<>();
		int count = 0;
		for (JsonElement el : files) {
			if (++count > MAX_FILES) break;
			JsonObject f = el.getAsJsonObject();
			String rel = f.get("path").getAsString().replace('\\', '/');
			String content = f.get("content").getAsString();
			if (!rel.startsWith("data/") || rel.contains("..") || rel.startsWith("/")) {
				throw new IOException("Недопустимый путь: " + rel);
			}
			if (ALLOWED_EXT.stream().noneMatch(rel::endsWith)) {
				throw new IOException("Недопустимое расширение: " + rel);
			}
			if (content.getBytes(StandardCharsets.UTF_8).length > MAX_FILE_BYTES) {
				throw new IOException("Файл слишком большой: " + rel);
			}
			Path target = root.resolve(rel).normalize();
			if (!target.startsWith(root)) throw new IOException("Путь выходит за пределы датапака: " + rel);
			Files.createDirectories(target.getParent());
			Files.writeString(target, content, StandardCharsets.UTF_8);
			written.add(rel);
		}
		return written;
	}
}
